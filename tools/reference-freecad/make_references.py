# Q01: reference parts built in FreeCAD (outside the product build). Run with FreeCAD's own
# interpreter; it writes the table that tests/differential/FreecadReferenceTests.cpp checks:
#
#   VOELUND_REFERENCE_TABLE=<output table> freecadcmd tools/reference-freecad/make_references.py
#
# (freecadcmd opens any further argument as a document, so the table comes from the environment)
#
# FreeCAD also uses OpenCASCADE, so this checks Völund's feature semantics (where a fillet,
# chamfer, hole, mirror, pattern, shell or revolve lands and what it makes), not the geometry kernel; the NIST parts
# (tests/differential/nist) are the kernel-independent reference.
import os

import FreeCAD
import Part

V = FreeCAD.Vector


def vertical_edges(shape):
    return [e for e in shape.Edges
            if len(e.Vertexes) == 2 and abs(e.Vertexes[0].Point.z - e.Vertexes[1].Point.z) > 1e-9]


def edges_at_height(shape, z):
    return [e for e in shape.Edges if all(abs(v.Point.z - z) < 1e-9 for v in e.Vertexes)]


def edge_at(shape, x, y):
    return [e for e in vertical_edges(shape)
            if all(abs(v.Point.x - x) < 1e-9 and abs(v.Point.y - y) < 1e-9 for v in e.Vertexes)]


def plate():
    # 80 x 50 x 12, the four vertical edges rounded R6, a through hole D10 at the centre.
    box = Part.makeBox(80, 50, 12)
    rounded = box.makeFillet(6, vertical_edges(box))
    return rounded.cut(Part.makeCylinder(5, 100, V(40, 25, -50)))


def blind_hole():
    # 60 x 40 x 20, a hole D8, 6 deep with a flat bottom, from the top at (15, 20).
    return Part.makeBox(60, 40, 20).cut(Part.makeCylinder(4, 6, V(15, 20, 14)))


def chamfered():
    # 40 x 30 x 20, the four top edges chamfered 2.
    box = Part.makeBox(40, 30, 20)
    return box.makeChamfer(2, edges_at_height(box, 20))


def mirrored():
    # 30 x 20 x 10 with its +X/+Y vertical edge rounded R4, mirrored about the YZ plane and
    # joined to the original.
    box = Part.makeBox(30, 20, 10)
    rounded = box.makeFillet(4, edge_at(box, 30, 20))
    return rounded.fuse(rounded.mirror(V(0, 0, 0), V(1, 0, 0))).removeSplitter()


def patterned():
    # 10 x 10 x 5, four copies along X 8 apart (overlapping by 2), joined.
    result = Part.makeBox(10, 10, 5)
    for index in range(1, 4):
        result = result.fuse(Part.makeBox(10, 10, 5, V(8 * index, 0, 0)))
    return result.removeSplitter()


def shelled():
    # 40 x 30 x 20, the top face opened, walls 2 thick inward.
    box = Part.makeBox(40, 30, 20)
    top = [f for f in box.Faces if abs(f.CenterOfMass.z - 20) < 1e-9]
    return box.makeThickness(top, -2, 1e-3)


def revolved():
    # The rectangle x 10..20, z 0..15 in the XZ plane, a full turn about Z.
    outline = Part.makePolygon([V(10, 0, 0), V(20, 0, 0), V(20, 0, 15), V(10, 0, 15),
                                V(10, 0, 0)])
    return Part.Solid(Part.Face(outline).revolve(V(0, 0, 0), V(0, 0, 1), 360))


PARTS = [("plate", plate), ("blind_hole", blind_hole), ("chamfered", chamfered),
         ("mirrored", mirrored), ("patterned", patterned), ("shelled", shelled),
         ("revolved", revolved)]

lines = ["# Q01: generated by tools/reference-freecad/make_references.py with FreeCAD %s" %
         ".".join(FreeCAD.Version()[:3]),
         "# part | volume mm3 | area mm2 | centroid x y z mm | faces"]
for name, build in PARTS:
    shape = build()
    if not shape.isValid() or len(shape.Solids) != 1:
        raise SystemExit("%s: not one valid solid" % name)
    c = shape.Solids[0].CenterOfMass
    lines.append("%s | %.9f | %.9f | %.9f %.9f %.9f | %d" %
                 (name, shape.Volume, shape.Area, c.x, c.y, c.z, len(shape.Faces)))
with open(os.environ["VOELUND_REFERENCE_TABLE"], "w", encoding="utf-8", newline="\n") as table:
    table.write("\n".join(lines) + "\n")
print("\n".join(lines))
